# frozen_string_literal: true

require_relative "../lib/synthient"

# Renders sig/synthient/models.rbs from the model and enum definitions, so
# the signatures and the decoders share one source.
module ModelsRBS
  def self.render
    constants = Synthient.constants.sort.map { |name| Synthient.const_get(name) }
    enums = constants.select do |value|
      value.instance_of?(Module) && value.constants.all? { |name| value.const_get(name).is_a?(String) }
    end
    models = constants.select { |value| value.is_a?(Class) && value.respond_to?(:fields) }
    body = enums.map { |enum| render_enum(enum) } + models.map { |model| render_model(model) }
    "# Generated by `rake sig` from the model definitions. Do not edit.\n\nmodule Synthient\n#{body.join("\n")}end\n"
  end

  def self.render_enum(enum)
    "  module #{short_name(enum)}\n#{enum.constants.sort.map { |name| "    #{name}: String\n" }.join}  end\n"
  end

  def self.render_model(model)
    fields = model.fields.map do |field|
      field.required ? [field.name, type(field.type)] : [field.name, "#{type(field.type)}?"]
    end
    params = model.fields.zip(fields).map { |field, (name, rbs)| "#{"?" unless field.required}#{name}: #{rbs}" }.join(", ")
    with = fields.map { |name, rbs| "?#{name}: #{rbs}" }.join(", ")
    <<~RBS.gsub(/^/, "  ")
      class #{short_name(model)} < Data
      #{fields.map { |name, rbs| "  attr_reader #{name}: #{rbs}\n" }.join.chomp}
        def self.new: (#{params}) -> instance
        def initialize: (#{params}) -> void
        def with: (#{with}) -> instance
      end
    RBS
  end

  def self.type(type)
    case type
    when :integer then "Integer"
    when :float then "Float"
    when :string, :bytes then "String"
    when :bool then "bool"
    when :unix_time, :time then "Time"
    when :date then "Date"
    when :ip then "IPAddr"
    when Array then "Array[#{type(type.first)}]"
    when Hash then "Hash[String, #{type(type.values.first)}]"
    else short_name(type)
    end
  end

  def self.short_name(constant)
    constant.name.delete_prefix("Synthient::")
  end
end
